/**
 * Exports the in-browser demo dataset for HireFlow Copilot, so the copilot reads exactly what the
 * demo board shows.
 *
 *   npx tsx scripts/export-demo-data.ts ../hireflow-copilot/src/hireflow_copilot/data/hireflow_web_demo.json
 *
 * Dates are written relative to today ("-3d@14" = three days ago at 14:00 UTC), the same way the
 * demo builds them, so neither side goes stale. Ids are deterministic, so ids in recorded copilot
 * answers match the board.
 */
import { writeFileSync } from 'node:fs'
import { createDemoStore } from '../src/demo/data'

const out = process.argv[2]
if (!out) {
  console.error('usage: npx tsx scripts/export-demo-data.ts <output.json>')
  process.exit(1)
}

const now = new Date()
const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate())

function relative(iso: string): string {
  const date = new Date(iso)
  const day = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate())
  const days = Math.round((day - today) / 86_400_000)
  return `${days >= 0 ? '+' : '-'}${Math.abs(days)}d@${date.getUTCHours()}`
}

const store = createDemoStore(now)

const data = {
  _comment: 'Generated by hireflow-web/scripts/export-demo-data.ts. Do not edit by hand.',
  companies: store.companies.map(({ id, name, industry, location }) => ({ id, name, industry, location })),
  jobs: store.jobs.map(({ createdAt: _c, publishedAt: _p, closedAt: _x, ...job }) => job),
  candidates: store.candidates.map(({ createdAt: _c, ...candidate }) => candidate),
  applications: store.applications.map((app) => ({
    id: app.id,
    jobPostingId: app.jobPostingId,
    candidateId: app.candidateId,
    stage: app.stage,
    coverLetter: app.coverLetter,
    appliedAt: relative(app.appliedAt),
    history: store.transitions
      .filter((t) => t.applicationId === app.id)
      .map((t) => ({ from: t.from, to: t.to, note: t.note, changedAt: relative(t.changedAt) })),
    interviews: store.interviews
      .filter((i) => i.applicationId === app.id)
      .map((i) => ({
        id: i.id,
        applicationId: i.applicationId,
        kind: i.kind,
        scheduledAt: relative(i.scheduledAt),
        durationMinutes: i.durationMinutes,
        interviewer: i.interviewer,
        rating: i.rating,
        feedback: i.feedback,
      })),
  })),
}

writeFileSync(out, `${JSON.stringify(data, null, 2)}\n`)
console.log(`Wrote ${out}: ${data.jobs.length} jobs, ${data.candidates.length} candidates, ${data.applications.length} applications`)
